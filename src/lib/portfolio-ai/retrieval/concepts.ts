type Form = readonly string[];

const compile = (forms: readonly string[]): Form[] =>
  forms.map((f) => tokenize(f)).filter((t) => t.length > 0);

const COMPILED = Object.fromEntries(
  Object.entries(CONCEPT_FORMS).map(([id, forms]) => [id, compile(forms)]),
) as Record<ConceptId, Form[]>;

const TECH = compile(TECH_TERMS);

/** Precomputed token variants of a question, reused by every matcher. */
export interface QueryTokens {
  tokens: string[];
  variants: Set<string>[];
}

export function prepare(tokens: string[]): QueryTokens {
  return { tokens, variants: tokens.map((t) => new Set(variants(t))) };
}

/** Index of the first occurrence of `form` (all tokens consecutive), or -1. */
function findForm(q: QueryTokens, form: Form): number {
  outer: for (let i = 0; i + form.length <= q.tokens.length; i++) {
    for (let j = 0; j < form.length; j++) {
      if (!q.variants[i + j]!.has(form[j]!)) continue outer;
    }
    return i;
  }
  return -1;
}

export function hasConcept(q: QueryTokens, id: ConceptId): boolean {
  return COMPILED[id].some((f) => findForm(q, f) >= 0);
}

export function matchConcepts(q: QueryTokens): Set<ConceptId> {
  const out = new Set<ConceptId>();
  for (const id of Object.keys(COMPILED) as ConceptId[]) if (hasConcept(q, id)) out.add(id);
  return out;
}

/** Technology terms named in the question, as written in TECH_TERMS (normalized). */
export function techTerms(q: QueryTokens): string[] {
  const found = TECH.filter((f) => findForm(q, f) >= 0).map((f) => f.join(' '));
  // Keep the most specific term: "agent orchestration" wins over "agent".
  return [...new Set(found)].filter((t) => !found.some((o) => o !== t && ` ${o} `.includes(` ${t} `)));
}

/** Matches arbitrary aliases (e.g. project names from the manifest) against the question. */
export function matchAlias(q: QueryTokens, aliases: readonly string[]): boolean {
  return compile(aliases).some((f) => findForm(q, f) >= 0);
}
