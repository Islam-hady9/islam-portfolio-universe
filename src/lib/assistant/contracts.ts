/**
 * Assistant integration contracts (spec §9.1). The UI depends only on these types, so the
 * deterministic demo provider can later be swapped for a grounded live backend
 * (e.g. FastAPI + retrieval over owner-approved, versioned knowledge) without UI changes.
 */
import type { SourceRef, VerificationStatus } from '@/content/schema';

export type AssistantMode = 'demo' | 'live';

export type ResponseStatus =
  | 'answered' // grounded answer with at least one source
  | 'out_of_scope' // no supporting source — honest "I don't know"
  | 'refused' // safety policy (injection attempt, private data request)
  | 'unavailable' // live backend not configured / down
  | 'rate_limited'
  | 'error';

export interface AskRequest {
  /** 1–500 characters after trimming (validated server-side by request-schema.ts). */
  question: string;
  /** Opaque per-tab id; never persisted server-side in the current gate. */
  sessionId?: string;
  locale?: 'en';
}

export interface SourceReference {
  kind: SourceRef['kind'];
  ref: string;
  label: string;
  href: string | null;
  verification: VerificationStatus;
}

export interface GroundedAnswer {
  mode: AssistantMode;
  status: ResponseStatus;
  answer: string;
  sources: SourceReference[];
  /** Knowledge entry used (demo) — supports regression evaluation sets later (spec §9.3). */
  entryId: string | null;
  /** Always shown with the answer. */
  disclaimer: string;
}

export interface SafetyPolicy {
  maxQuestionLength: number;
  /** Answers must cite at least one source or return out_of_scope. */
  requireCitations: true;
  /** Inputs are never stored in this gate (spec §8.3). */
  storeInputs: false;
  injectionPatterns: RegExp[];
  privateDataPatterns: RegExp[];
}

/** Resolves a content source reference to a human label + link (built server-side from content). */
export type SourceIndex = Record<string, Omit<SourceReference, 'kind' | 'ref'>>;

export const sourceKey = (s: Pick<SourceRef, 'kind' | 'ref'>) => `${s.kind}:${s.ref}`;

export interface AssistantClient {
  readonly mode: AssistantMode;
  ask(request: AskRequest): Promise<GroundedAnswer>;
}

