// Imports the owner's résumé PDF byte-for-byte and records its integrity.
//
// Usage: npm run resume:import -- <path-to-pdf> [--name=Islam_Abdelhady_CV.pdf]
//
// Copies the file unchanged to public/resume/<name> (served as /resume/<name>), verifies the
// SHA-256 of source and copy are identical, and writes src/assets/resume.json (path, size,
// checksum). The PDF is never parsed, re-saved, compressed or rewritten. Replacing the CV later
// is the same command with the new file; every page reads the path from content/manifest.
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const [src, ...rest] = process.argv.slice(2);
if (!src) {
  console.error('usage: npm run resume:import -- <path-to-pdf> [--name=Islam_Abdelhady_CV.pdf]');
  process.exit(2);
}
const name = (rest.find((a) => a.startsWith('--name=')) ?? '--name=Islam_Abdelhady_CV.pdf').slice(7);
if (!/^[A-Za-z0-9._-]+\.pdf$/.test(name)) throw new Error(`Unsafe public file name: ${name}`);

const sha256 = (file) => createHash('sha256').update(readFileSync(file)).digest('hex');
const bytes = readFileSync(src);
if (bytes.subarray(0, 5).toString('latin1') !== '%PDF-') throw new Error(`${src} is not a PDF`);

const before = sha256(src);
const dir = join('public', 'resume');
mkdirSync(dir, { recursive: true });
const dest = join(dir, name);
copyFileSync(src, dest); // byte-for-byte; no transformation of any kind
const after = sha256(dest);
if (before !== after) throw new Error(`Checksum mismatch after copy: ${before} ≠ ${after}`);

const manifest = {
  $comment: 'Generated by scripts/resume/import-resume.mjs — do not edit by hand.',
  src: `/resume/${name}`,
  fileName: name,
  sourceFileName: basename(src),
  bytes: statSync(dest).size,
  sha256: after,
  importedOn: new Date().toISOString().slice(0, 10),
};
writeFileSync(join('src', 'assets', 'resume.json'), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`source  ${before}  ${src}`);
console.log(`copy    ${after}  ${dest}  (${manifest.bytes} bytes)`);
console.log('identical: yes');
